"""Summary of the team tables for the documentation.

`summarise` reduces the three tables to the figures quoted in docs/app.md; the build script saves
them to reports/team_tables.json (tracked: aggregates only, after small-cell suppression).
`render_block` turns that summary into the generated section of docs/app.md, so the figures in
the documentation are never typed by hand. tests/test_docs.py checks that the two agree.
"""

import math

import pandas as pd

from sar.config import CUTOFF_DAY
from sar.data.split import TEST_PRESENTATION
from sar.service.views import MIN_CELL
from sar.tables import department, funnel, profiles

START = ("<!-- team-tables:start. Generated by scripts/build_team_tables.py from reports/team_tables.json; "
         "do not edit by hand. -->")
END = "<!-- team-tables:end -->"


def _clean(value):
    if value is pd.NA:
        return None
    if isinstance(value, float):
        return None if math.isnan(value) else round(value, 4)
    if hasattr(value, "item"):
        return _clean(value.item())
    return value


def _records(df: pd.DataFrame, columns) -> list[dict]:
    return [{c: _clean(v) for c, v in row.items()} for row in df[list(columns)].to_dict("records")]


def summarise(dept: pd.DataFrame, fun: pd.DataFrame, prof: pd.DataFrame, selection: pd.DataFrame,
              k: int) -> dict:
    val = dept[dept["code_presentation"] == TEST_PRESENTATION]
    alls = fun[fun["code_module"] == funnel.ALL_MODULES]
    return {
        "dataset": ("OULAD, released under CC-BY 4.0 (https://creativecommons.org/licenses/by/4.0/); "
                    "Kuzilek J., Hlosta M., Zdrahal Z. Open University Learning Analytics dataset Sci. Data 4:170171 doi: 10.1038/sdata.2017.171 (2017)."),
        "cutoff_day": CUTOFF_DAY, "min_cell": MIN_CELL, "validation_presentation": TEST_PRESENTATION,
        "department_risk": {
            "rows": len(dept), "suppressed_rows": int(dept["suppressed"].sum()),
            "validation": _records(val, ["code_module", "students", "at_risk_rate", *department.BAND_SHARES]),
        },
        "retention_funnel": {
            "rows": len(fun), "suppressed_rows": int(fun["suppressed"].sum()),
            "not_applicable": _records(fun.loc[~fun["applicable"].astype(bool)].sort_values(
                ["code_module", "code_presentation"]), ["code_module", "code_presentation", "stage"]),
            "all_modules": _records(alls, ["code_presentation", "stage_order", "stage", "students",
                                           "share_of_registered"]),
        },
        "student_profiles": {
            "features": list(profiles.PROFILE_FEATURES), "log_features": list(profiles.LOG_FEATURES),
            "k_range": list(profiles.K_RANGE), "k": int(k),
            "selection": _records(selection, ["k", "silhouette", "smallest_share"]),
            "profiles": _records(prof, ["scope", "profile", "students", "share_of_scope", "at_risk_rate",
                                        *(f"mean_{f}" for f in profiles.PROFILE_FEATURES), "description"]),
        },
    }


def _pct(x) -> str:
    return "hidden" if x is None else f"{x:.0%}"


def _count(x) -> str:
    return "hidden" if x is None else f"{x:,}"


def render_block(s: dict) -> str:
    val, d, f, p = s["validation_presentation"], s["department_risk"], s["retention_funnel"], s["student_profiles"]
    lines = [START, "", f"Figures from the last run of `scripts/build_team_tables.py`. Groups and counts under "
             f"{s['min_cell']} students are hidden. Source: {s['dataset'].rstrip('.')}.", ""]

    lines += [f"#### Department risk, {val} (validation)", "",
              "| Module | Students | At-risk rate | Low | Medium | High |", "|---|---:|---:|---:|---:|---:|"]
    for r in d["validation"]:
        lines.append(f"| {r['code_module']} | {_count(r['students'])} | {_pct(r['at_risk_rate'])} | "
                     + " | ".join(_pct(r[b]) for b in department.BAND_SHARES) + " |")
    lines += ["", f"Rows in the table (all presentations): {d['rows']}; hidden: {d['suppressed_rows']}.", ""]

    pres = sorted({r["code_presentation"] for r in f["all_modules"]})
    lines += ["#### Retention funnel, all modules", "",
              "Students at each stage, with the share of registered students in brackets.", "",
              "| Stage | " + " | ".join(pres) + " |", "|---|" + "---:|" * len(pres)]
    by = {(r["code_presentation"], r["stage_order"]): r for r in f["all_modules"]}
    for order, (_, label) in enumerate(funnel.STAGES, 1):
        cells = [by[(q, order)] for q in pres]
        lines.append(f"| {label} | " + " | ".join(f"{_count(c['students'])} ({_pct(c['share_of_registered'])})"
                                                  for c in cells) + " |")
    na = ", ".join(f"{r['code_module']} {r['code_presentation']}" for r in f["not_applicable"]) or "none"
    lines += ["", f"Submission stage not applicable (no assessment due by Day {s['cutoff_day']}; previous count "
              f"carried forward, also in the totals above): {na}. Rows in the table: {f['rows']}; "
              f"hidden counts: {f['suppressed_rows']}.", ""]

    lines += ["#### Student profiles", "", "| k | Silhouette | Smallest cluster (share of training rows) |",
              "|---:|---:|---:|"]
    lines += [f"| {r['k']} | {r['silhouette']:.3f} | {_pct(r['smallest_share'])} |" for r in p["selection"]]
    lines += ["", f"Chosen: k = {p['k']}.", "",
              f"| Profile | {val} students | Share | At-risk rate | Mean clicks | Mean active days | "
              f"Mean days without activity before Day {s['cutoff_day']} | Mean submitted | Mean missed | "
              "At-risk rate (training) |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    train = {r["profile"]: r for r in p["profiles"] if r["scope"] == "training"}
    rows = [r for r in p["profiles"] if r["scope"] == "validation"]
    for r in rows:
        m = [r[f"mean_{x}"] for x in profiles.PROFILE_FEATURES]
        nums = (["hidden"] * 5 if m[0] is None else
                [f"{m[0]:,.0f}", f"{m[1]:.1f}", f"{m[2]:.1f}", f"{m[3]:.2f}", f"{m[4]:.2f}"])
        lines.append(f"| {r['profile']} | {_count(r['students'])} | {_pct(r['share_of_scope'])} | "
                     f"{_pct(r['at_risk_rate'])} | " + " | ".join(nums)
                     + f" | {_pct(train.get(r['profile'], {}).get('at_risk_rate'))} |")
    lines += [""] + [f"- **{r['profile']}**: {r['description']}" for r in rows if r["description"]]
    lines += ["", END]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """Put `block` between the START and END markers of `text`."""
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def current_block(text: str) -> str:
    """The generated section of `text`, markers included."""
    return START + text.split(START, 1)[1].split(END, 1)[0] + END
